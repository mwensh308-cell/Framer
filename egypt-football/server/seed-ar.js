export function applyArabic() {
  for (const [slug, summary] of Object.entries(ERAS)) run('UPDATE eras SET summary_ar = ? WHERE slug = ?', summary, slug);
  for (const [slug, [nick, city, stadium, history]] of Object.entries(CLUBS)) {
    run('UPDATE clubs SET nickname_ar = ?, city_ar = ?, stadium_ar = ?, history_ar = ? WHERE slug = ?', nick, city, stadium, history, slug);
  }
  for (const [en, ar] of Object.entries(MILESTONES)) run('UPDATE club_milestones SET title_ar = ? WHERE title_en = ?', ar, en);
  for (const [slug, [nick, place, bio]] of Object.entries(PLAYERS)) {
    run('UPDATE players SET nickname_ar = ?, birthplace_ar = ?, bio_ar = ? WHERE slug = ?', nick, place, bio, slug);
  }
  for (const [en, ar] of Object.entries(FOREIGN_CLUBS)) run('UPDATE player_spells SET club_name_ar = ? WHERE club_name = ?', ar, en);
  for (const [slug, s] of Object.entries(COMPETITIONS)) run('UPDATE competitions SET summary_ar = ? WHERE slug = ?', s, slug);
  for (const [slug, s] of Object.entries(TEAMS)) run('UPDATE national_teams SET summary_ar = ? WHERE slug = ?', s, slug);
  for (const [en, ar] of Object.entries(PLACES)) {
    run('UPDATE titles SET runner_up_ar = ? WHERE runner_up = ?', ar, en);
    run('UPDATE titles SET host_ar = ? WHERE host = ?', ar, en);
    run('UPDATE tournament_appearances SET host_ar = ? WHERE host = ?', ar, en);
  }
  for (const [en, ar] of Object.entries(COACHES)) run('UPDATE tournament_appearances SET coach_ar = ? WHERE coach = ?', ar, en);
  for (const [key, note] of Object.entries(APPEARANCE_NOTES)) {
    const [tournament, year] = key.split('|');
    run('UPDATE tournament_appearances SET notes_ar = ? WHERE tournament = ? AND year = ?', note, tournament, Number(year));
  }
  for (const [date, [title, body = null]] of Object.entries(EVENTS)) run('UPDATE events SET title_ar = ?, body_ar = ? WHERE date = ?', title, body, date);
}
